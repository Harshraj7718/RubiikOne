// Builds the Razorpay checkout logo: the RUBIIK double-I emblem in gold on ink, 256×256 (the size
// Razorpay recommends). Writes src/assets/razorpay-logo.png and src/assets/razorpayLogo.js, which
// exports it as a data URL: Razorpay's window ignores image links it can't fetch over https (such as
// localhost), but always shows an embedded image. Run with: node tools/razorpay-logo.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">
  <defs>
    <linearGradient id="gold" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#f3dfae"/>
      <stop offset="0.55" stop-color="#8c6a35"/>
      <stop offset="1" stop-color="#d9b979"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.45" r="0.6">
      <stop offset="0" stop-color="#1c2a3a"/>
      <stop offset="1" stop-color="#0B1219"/>
    </radialGradient>
  </defs>
  <rect width="256" height="256" fill="url(#glow)"/>
  <rect x="14" y="14" width="228" height="228" fill="none" stroke="#C9A464" stroke-opacity="0.55" stroke-width="2"/>
  <rect x="22" y="22" width="212" height="212" fill="none" stroke="#C9A464" stroke-opacity="0.22" stroke-width="1"/>
  <!-- The emblem from src/components/Logo.jsx (viewBox 40×100), scaled to 150px tall and centred -->
  <g transform="translate(98 53) scale(1.5)">
    <path d="M6 0h7l-1.2 100h-4.6zM27 0h7l-1.2 100h-4.6z" fill="url(#gold)"/>
  </g>
</svg>`;

const out = fileURLToPath(new URL("../src/assets/razorpay-logo.png", import.meta.url));
// A 64-colour palette keeps the gold gradient smooth at a fraction of the size.
const png = await sharp(Buffer.from(svg)).png({ palette: true, colours: 64, compressionLevel: 9 }).toBuffer();
writeFileSync(out, png);
writeFileSync(
  fileURLToPath(new URL("../src/assets/razorpayLogo.js", import.meta.url)),
  `// Generated by tools/razorpay-logo.mjs from the RUBIIK emblem; do not edit by hand.
export default "data:image/png;base64,${png.toString("base64")}";
`,
);
console.log("wrote", out, png.length, "bytes");
